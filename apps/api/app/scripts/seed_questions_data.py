def _build_mbti_questions() -> list[dict[str, Any]]:
    questions: list[dict[str, Any]] = []
    order = 0
    for (pole_a, pole_b), items in _MBTI_ITEMS.items():
        for text_a, text_b in items:
            questions.append(
                {
                    "kind": "forced_choice",
                    "dimension": f"{pole_a}{pole_b}",
                    "text": f"کدام جمله بیشتر توصیف کننده شماست؟",
                    "order_index": order,
                    "is_reverse_scored": False,
                    "options": [
                        {"label": text_a, "value": 1, "pole": pole_a, "weight": 1.0, "order_index": 0},
                        {"label": text_b, "value": 2, "pole": pole_b, "weight": 1.0, "order_index": 1},
                    ],
                }
            )
            order += 1
    return questions



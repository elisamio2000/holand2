RIASEC_DIMENSIONS = ["R", "I", "A", "S", "E", "C"]


def _build_holland_questions() -> list[dict[str, Any]]:
    questions: list[dict[str, Any]] = []
    order = 0
    for dim in RIASEC_DIMENSIONS:
        for text in _HOLLAND_STATEMENTS[dim]:
            questions.append(
                {
                    "kind": "likert",
                    "dimension": dim,
                    "text": text,
                    "order_index": order,
                    "is_reverse_scored": False,
                    "options": [
                        {
                            "label": label,
                            "value": value,
                            "pole": dim,
                            "weight": float(value),
                            "order_index": value - 1,
                        }
                        for value, label in LIKERT_LABELS
                    ],
                }
            )
            order += 1
    return questions


